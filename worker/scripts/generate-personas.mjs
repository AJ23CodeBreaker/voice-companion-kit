// Reads the persona/behavior .txt files in personas/ and generates a TS module
// with them embedded as string constants. The .txt files stay the single source
// of truth — edit those, then re-run this before deploy. Wired as a
// predeploy/predev/pretest step, so `npm run build` is usually enough.
//
// Why generate instead of reading at runtime: a Worker has no filesystem. The
// alternative is a KV lookup on every cold start, for text that changes once a
// week. Embedding it also means a bad persona edit fails the build rather than
// the first conversation after deploy.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const PERSONA_DIR = join(__dirname, "..", "personas");
const OUT_FILE = join(__dirname, "..", "src", "personas.generated.ts");

function readText(filename) {
  // Normalise CRLF to LF. core.autocrlf=true rewrites these .txt files on
  // checkout, and a stray carriage return changes the system prompt
  // byte-for-byte, silently invalidating the shared cached prefix.
  return readFileSync(join(PERSONA_DIR, filename), "utf-8")
    .split("\r\n").join("\n")
    .trim();
}

/**
 * Reads a line-per-entry list file (the greeting files). Blank lines and
 * #-comments are stripped, so the files can carry their own editing rules
 * at the top without those ending up in someone's ears.
 */
function readLines(filename) {
  return readText(filename)
    .split(/\r?\n/)
    .map((l) => l.trim())
    .filter((l) => l && !l.startsWith("#"));
}

// Re-indents a JSON.stringify block so the generated file stays readable.
function indentBlock(text, spaces) {
  const pad = " ".repeat(spaces);
  return text.split("\n").join("\n" + pad);
}

function tsString(s) {
  // Template literal — escape backtick, backslash, and ${
  return "`" + s.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${") + "`";
}

const behavior = readText("behavior.txt");

// id -> { name, desc, personaFile, greetings, voiceId, isAiCharacter }
//
// ONE character ships here on purpose. The shape is what matters, and a second
// one teaches nothing a first does not. Add yours by writing two files in
// personas/ and adding a row — no frontend change is needed, because `desc` is
// served by /characters rather than hardcoded in the page.
//
// voiceId is a TTS provider voice identifier, not a secret, but it is also not
// portable: it names a voice in YOUR provider account. Put your own in here.
// The empty string is deliberate — src/session.ts refuses to start a session
// without a voice and says so, which is a better failure than silence.
const CHAR_DEFS = [
  {
    id: "demo",
    name: "Mara",
    desc: "A bookshop manager who asks better questions than she answers",
    file: "persona_demo.txt",
    greetings: "greetings_demo.txt",
    voiceId: "",        // <- your TTS provider's voice id
    isAi: false,
  },
];
let out = `// AUTO-GENERATED by scripts/generate-personas.mjs — do not edit by hand.
// Source of truth: personas/*.txt — edit those, then run
// \`npm run build\` (or \`node scripts/generate-personas.mjs\`) to regenerate.

export interface Character {
  id: string;
  name: string;
  desc: string;         // one-line UI description, served by /characters
  systemPrompt: string;
  voiceId: string;      // TTS provider voice id; may be overridden by env — see session.ts
  voiceIdLiteral: string | null;
  isAiCharacter: boolean;
  /**
   * Startup greetings — spoken during the loading bar, before the user has
   * said anything. Never sent to the LLM; they go straight to TTS. Source:
   * personas/greetings_*.txt, which carry their own editing rules.
   */
  greetings: string[];
}

export const BEHAVIOR: string = ${tsString(behavior)};

export const CHARACTERS: Record<string, Character> = {
`;

for (const c of CHAR_DEFS) {
  const persona = readText(c.file);
  const greetings = readLines(c.greetings);
  if (greetings.length === 0) throw new Error(`${c.greetings} has no greeting lines`);
  const systemPrompt = `${persona}\n\n${behavior}`;
  out += `  ${c.id}: {
    id: ${JSON.stringify(c.id)},
    name: ${JSON.stringify(c.name)},
    desc: ${JSON.stringify(c.desc)},
    systemPrompt: ${tsString(systemPrompt)},
    voiceId: ${c.voiceId ? JSON.stringify(c.voiceId) : "''"},
    voiceIdLiteral: ${c.voiceId ? JSON.stringify(c.voiceId) : "null"},
    isAiCharacter: ${c.isAi},
    greetings: ${indentBlock(JSON.stringify(greetings, null, 6), 4)},
  },
`;
}

out += `};

export const DEFAULT_CHARACTER = "demo";
`;

writeFileSync(OUT_FILE, out, "utf-8");
const greetingTotal = CHAR_DEFS.reduce((n, c) => n + readLines(c.greetings).length, 0);
console.log(
  `Generated ${OUT_FILE} (${CHAR_DEFS.length} characters, ${greetingTotal} greetings, behavior.txt: ${behavior.length} chars)`,
);
